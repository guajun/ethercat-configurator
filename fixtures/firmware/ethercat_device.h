#ifndef LAN9252_BASIC_ETHERCAT_DEVICE_H
#define LAN9252_BASIC_ETHERCAT_DEVICE_H

#include <stdint.h>

#if defined(__GNUC__)
#define LAN9252_BASIC_PACKED __attribute__((packed))
#else
#define LAN9252_BASIC_PACKED
#endif

#if defined(_MSC_VER)
#pragma pack(push, 1)
#endif

#define LAN9252_BASIC_VENDOR_ID 0x00000A88U
#define LAN9252_BASIC_PRODUCT_CODE 0x00000001U
#define LAN9252_BASIC_REVISION 0x00000001U

#define LAN9252_BASIC_RX_PDI_ADDRESS 0x1000U
#define LAN9252_BASIC_RX_REQUIRED_BYTES 3U
#define LAN9252_BASIC_RX_BUFFER_BYTES 256U

#define LAN9252_BASIC_TX_PDI_ADDRESS 0x1100U
#define LAN9252_BASIC_TX_REQUIRED_BYTES 3U
#define LAN9252_BASIC_TX_BUFFER_BYTES 256U

#define LAN9252_BASIC_RX_CONTROL_WORD_INDEX 0x7000U
#define LAN9252_BASIC_RX_CONTROL_WORD_SUBINDEX 0x01U
#define LAN9252_BASIC_RX_CONTROL_WORD_BYTE_OFFSET 0U
#define LAN9252_BASIC_RX_CONTROL_WORD_BIT_OFFSET 0U
#define LAN9252_BASIC_RX_CONTROL_WORD_BIT_LENGTH 16U
#define LAN9252_BASIC_RX_CONTROL_WORD_BYTE_LENGTH 2U
#define LAN9252_BASIC_RX_CONTROL_WORD_BIT_MASK 0xFFFFU

#define LAN9252_BASIC_RX_ENABLE_OUTPUT_INDEX 0x7000U
#define LAN9252_BASIC_RX_ENABLE_OUTPUT_SUBINDEX 0x02U
#define LAN9252_BASIC_RX_ENABLE_OUTPUT_BYTE_OFFSET 2U
#define LAN9252_BASIC_RX_ENABLE_OUTPUT_BIT_OFFSET 16U
#define LAN9252_BASIC_RX_ENABLE_OUTPUT_BIT_LENGTH 1U
#define LAN9252_BASIC_RX_ENABLE_OUTPUT_BYTE_LENGTH 1U
#define LAN9252_BASIC_RX_ENABLE_OUTPUT_BIT_MASK 0x1U

#define LAN9252_BASIC_TX_STATUS_WORD_INDEX 0x6000U
#define LAN9252_BASIC_TX_STATUS_WORD_SUBINDEX 0x01U
#define LAN9252_BASIC_TX_STATUS_WORD_BYTE_OFFSET 0U
#define LAN9252_BASIC_TX_STATUS_WORD_BIT_OFFSET 0U
#define LAN9252_BASIC_TX_STATUS_WORD_BIT_LENGTH 16U
#define LAN9252_BASIC_TX_STATUS_WORD_BYTE_LENGTH 2U
#define LAN9252_BASIC_TX_STATUS_WORD_BIT_MASK 0xFFFFU

#define LAN9252_BASIC_TX_INPUT_READY_INDEX 0x6000U
#define LAN9252_BASIC_TX_INPUT_READY_SUBINDEX 0x02U
#define LAN9252_BASIC_TX_INPUT_READY_BYTE_OFFSET 2U
#define LAN9252_BASIC_TX_INPUT_READY_BIT_OFFSET 16U
#define LAN9252_BASIC_TX_INPUT_READY_BIT_LENGTH 1U
#define LAN9252_BASIC_TX_INPUT_READY_BYTE_LENGTH 1U
#define LAN9252_BASIC_TX_INPUT_READY_BIT_MASK 0x1U

typedef struct LAN9252_BASIC_PACKED
{
    uint16_t control_word;
    uint8_t reserved_tail[1];
} RxProcessData;

typedef union
{
    uint8_t bytes[LAN9252_BASIC_RX_REQUIRED_BYTES];
    RxProcessData fields;
} RxProcessBuffer;

typedef struct LAN9252_BASIC_PACKED
{
    uint16_t status_word;
    uint8_t reserved_tail[1];
} TxProcessData;

typedef union
{
    uint8_t bytes[LAN9252_BASIC_TX_REQUIRED_BYTES];
    TxProcessData fields;
} TxProcessBuffer;

#if defined(__STDC_VERSION__) && (__STDC_VERSION__ >= 201112L)
_Static_assert(sizeof(RxProcessData) == LAN9252_BASIC_RX_REQUIRED_BYTES, "RX process data size mismatch");
_Static_assert(sizeof(TxProcessData) == LAN9252_BASIC_TX_REQUIRED_BYTES, "TX process data size mismatch");
_Static_assert(3U == LAN9252_BASIC_RX_REQUIRED_BYTES, "RX generated layout changed");
_Static_assert(3U == LAN9252_BASIC_TX_REQUIRED_BYTES, "TX generated layout changed");
#endif

#if defined(_MSC_VER)
#pragma pack(pop)
#endif

#undef LAN9252_BASIC_PACKED

#endif /* LAN9252_BASIC_ETHERCAT_DEVICE_H */
